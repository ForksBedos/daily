"""Извлечение реквизитов актов из свободного текста (docs/plan/stage-3-dedup.md, задача 3.3).

Большинство случаев — дословные фразы из материалов, собранных 02.11.2026.
"""

import pytest

from uzdigest.legal.doc_key import find_refs


def keys(text, year=2026):
    return [r.doc_key for r in find_refs(text, year)]


