def test_year_guessed_when_no_date_nearby():
    [ref] = find_refs("Ҳуқуқий асос: “Коррупцияга қарши курашиш тўғрисида”ги Қонун (ЎРҚ-419).", 2026)
    assert (ref.doc_key, ref.year_guessed) == ("ZRU-419-2026", True)
    [dated] = find_refs("Указ № УП-236 от 28.10.2026", 2027)
    assert (dated.year, dated.year_guessed) == (2026, False)


def test_year_only_and_dates_of_neighbouring_acts():
    # nuz: только год, без дня и месяца
    [ref] = find_refs(
        "создан постановлением Кабинета Министров Республики Узбекистан № 440 от 2019 года.", 2026
    )
    assert (ref.doc_key, ref.year_guessed) == ("PKM-440-2019", False)
    # imv: дата после ЎРҚ-1155 относится к нему, а не к ЎРҚ-419 перед ним
    text = "Қонун (ЎРҚ-419); ЎРҚ-1155-сон Қонун (22.06.2026); Президентнинг ПҚ-240-сон қарори (11.05.2022)."
    refs = {r.doc_key: r.year_guessed for r in find_refs(text, 2026)}
    assert refs == {"ZRU-419-2026": True, "ZRU-1155-2026": False, "PP-240-2022": False}
    # повтор того же акта между номером и датой не мешает
    [ref] = find_refs("Указ УП-236 (см. УП-236 от 28.10.2025) действует", 2026)
    assert (ref.doc_key, ref.year_guessed) == ("UP-236-2025", False)


def test_nearest_date_wins():
    text = "Постановление от 15.05.2025 № 318 изменено постановлением Кабмина № 596 от 29.10.2026."
    assert keys(text) == ["PKM-596-2026"]  # «№ 318» без Кабмина перед ним не считается
    text = "ПП-371 от 13.10.2026 г. и ПП-387 от 27.10.2025 г."
    assert keys(text) == ["PP-371-2026", "PP-387-2025"]


def test_one_ref_per_doc_key_in_order():
    text = "Указ УП-236 от 28.10.2026. Как сказано в УП-236 от 28.10.2026, выплаты… ПП-387 от 27.10.2026"
    refs = find_refs(text, 2026)
    assert [r.doc_key for r in refs] == ["UP-236-2026", "PP-387-2026"]
    assert refs[0].position < refs[1].position
    assert "УП-236" in refs[0].raw_mention


def test_draft_is_flagged():
    [draft] = find_refs("На обсуждение вынесен проект постановления ПКМ № 612 от 30.10.2026", 2026)
    assert draft.is_draft
    [draft] = find_refs("Проект указа (УП-240 от 01.11.2026) размещён на regulation.gov.uz", 2026)
    assert draft.is_draft
    [real] = find_refs(
        "Рассмотрен ход реализации инвестиционных проектов. ПП-387 от 27.10.2026 предусматривает", 2026
    )
    assert not real.is_draft
